namespace InfiniteToken.Lumber;

/// <summary>Lumber's log levels. The numbers are the Lumber API's.</summary>
public enum LumberLevel
{
    /// <summary>DEBUG (0).</summary>
    Debug = 0,

    /// <summary>INFO (1).</summary>
    Info = 1,

    /// <summary>WARN (2).</summary>
    Warn = 2,

    /// <summary>ERROR (3).</summary>
    Error = 3,

    /// <summary>FATAL (4).</summary>
    Fatal = 4,
}
